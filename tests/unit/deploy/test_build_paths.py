"""Pins for the removal of ``libs/market-protocol`` from the build and CI files.

The library left the repository (``FORK-CN.md``) but stayed in two Dockerfiles, two Compose bind
mounts and three workflows, so the image behind ``make up`` could not be built. Three guards, all
deliberately literal: none parses Dockerfile or YAML, and what they cannot read they refuse.

1. Nothing under ``deploy/``, ``docker-compose*.yml``, ``.github/workflows/``, the ``Makefile`` or
   ``scripts/`` contains the library's name, and each of those files is UTF-8 text.
2. The ``COPY``/``ADD`` lines of the two backend Dockerfiles are an exact list. A line that is
   added, removed or reworded fails the test until the list is updated by someone who has read
   the line, and every source the list names must exist.
3. In each of them the copy of ``skills/agent-browser`` comes before the first ``uv sync`` (the
   first line that is not a comment and has those two words, whatever follows them).

The search skips bytecode caches (``__pycache__``): they are generated by running Python in the
tree, are not text, and a checkout where the suite has run has them.
"""

from __future__ import annotations

import glob
import re
import shlex
import shutil
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]

# The names of the removed library, as a path or directory (market-protocol) and as a module.
REMOVED = ("market-protocol", "market_protocol")


def _scanned(root: Path) -> list[Path]:
    """Every build, Compose, CI and script file under ``root``, bytecode caches excepted."""
    files = [p for p in (root / "deploy").rglob("*") if p.is_file()]
    files += root.glob("*compose*.y*ml")
    files += [p for p in (root / ".github/workflows").rglob("*") if p.is_file()]
    files += [root / "Makefile"]
    files += [p for p in (root / "scripts").rglob("*") if p.is_file()]
    return sorted(
        p for p in files if "__pycache__" not in p.parts and p.suffix != ".pyc"
    )


def _offences(root: Path) -> list[str]:
    """Files that name the removed library, or that cannot be read as UTF-8 text."""
    found = []
    for path in _scanned(root):
        relative = path.relative_to(root)
        try:
            text = path.read_bytes().decode("utf-8")
        except UnicodeDecodeError:
            found.append(f"{relative}: not UTF-8, so it cannot be searched")
            continue
        found += [f"{relative}: names {name}" for name in REMOVED if name in text]
    return found


def test_no_build_or_ci_file_names_the_removed_library():
    scanned = {str(p.relative_to(ROOT)) for p in _scanned(ROOT)}
    # A scan that quietly found nothing would pass for the wrong reason.
    assert {
        "deploy/Dockerfile.backend",
        "deploy/Dockerfile.dev",
        "docker-compose.yml",
        ".github/workflows/test.yml",
        "Makefile",
        "scripts/start_db.sh",
    } <= scanned
    assert _offences(ROOT) == []


@pytest.fixture
def copy_of_the_tree(tmp_path):
    """The scanned files, copied to a temporary directory so a test can edit them."""
    for path in _scanned(ROOT):
        target = tmp_path / path.relative_to(ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
    return tmp_path


def test_the_copy_the_mutations_below_edit_is_clean(copy_of_the_tree):
    assert _offences(copy_of_the_tree) == []


@pytest.mark.parametrize("name", REMOVED)
@pytest.mark.parametrize(
    "relative",
    [
        "deploy/Dockerfile.backend",
        "deploy/Dockerfile.dev",
        "docker-compose.yml",
        ".github/workflows/test.yml",
        ".github/workflows/sandbox-integration.yml",
        "Makefile",
        "scripts/start_db.sh",
    ],
)
def test_putting_the_name_back_fails_the_search(copy_of_the_tree, relative, name):
    path = copy_of_the_tree / relative
    path.write_text(path.read_text() + f"\n# libs/{name}/\n")
    assert _offences(copy_of_the_tree) == [f"{relative}: names {name}"]


def test_bytecode_caches_are_not_searched(copy_of_the_tree):
    # A checkout where the suite has run has these under scripts/ and deploy/.
    cache = copy_of_the_tree / "scripts/__pycache__"
    cache.mkdir()
    (cache / "x.cpython-313.pyc").write_bytes(b"\xf3\r\r\n\xff market-protocol")
    assert _offences(copy_of_the_tree) == []


def test_a_file_that_is_not_utf8_fails_the_search(copy_of_the_tree):
    path = copy_of_the_tree / "deploy/Dockerfile.dev"
    path.write_bytes(path.read_bytes() + b"\n# \xff\xfe market-protocol\n")
    assert _offences(copy_of_the_tree) == [
        "deploy/Dockerfile.dev: not UTF-8, so it cannot be searched"
    ]


