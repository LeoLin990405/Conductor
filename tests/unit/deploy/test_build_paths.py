# `uv sync` builds the root project before `src/` is copied, and hatchling refuses an editable
# build whose `force-include` source (pyproject.toml) is missing, so this copy must come first.
SKILL_COPY = "COPY skills/agent-browser/ skills/agent-browser/"
FIRST_SYNC = "uv sync --frozen"
# Any `uv sync`, not only the frozen one: an install with other options also needs the copy.
UV_SYNC = re.compile(r"\buv\s+sync\b")


def _copy_and_add_lines(dockerfile: Path) -> list[str]:
    """Lines that start a ``COPY`` or ``ADD`` (any case), exactly as written."""
    return [
        line.strip()
        for line in dockerfile.read_text().splitlines()
        if line.strip().split(None, 1)[:1]
        and line.strip().split(None, 1)[0].upper() in ("COPY", "ADD")
    ]


def _sources_of(line: str) -> list[str]:
    """The build-context sources of one listed ``COPY`` line (``--from`` copies have none)."""
    words = shlex.split(line)[1:]
    if any(w.startswith("--from=") for w in words):
        return []
    return [w.rstrip("/") for w in words if not w.startswith("--")][:-1]


def _context_path_exists(path: str) -> bool:
    return bool(glob.glob(str(ROOT / path)))


@pytest.mark.parametrize("dockerfile", COPY_LINES)
def test_the_copy_lines_are_the_listed_ones(dockerfile):
    actual = _copy_and_add_lines(ROOT / dockerfile)
    listed = [line for line, _paths in COPY_LINES[dockerfile]]
    added = [line for line in actual if line not in listed]
    removed = [line for line in listed if line not in actual]
    assert actual == listed, (
        f"{dockerfile} COPY/ADD lines differ from the list in {Path(__file__).name}: "
        f"added {added}, removed {removed}. Check that each source of a new line exists "
        "in the repository, then update COPY_LINES."
    )


@pytest.mark.parametrize("dockerfile", COPY_LINES)
def test_the_listed_paths_are_the_sources_of_their_lines(dockerfile):
    # The existence check below reads the paths, so they must be the line's own sources.
    for line, paths in COPY_LINES[dockerfile]:
        assert [p.rstrip("/") for p in paths] == _sources_of(line), line


@pytest.mark.parametrize("dockerfile", COPY_LINES)
def test_every_listed_source_exists(dockerfile):
    missing = [
        path
        for _line, paths in COPY_LINES[dockerfile]
        for path in paths
        if not _context_path_exists(path)
    ]
    assert missing == [], (
        f"{dockerfile} copies paths the repository does not have: {missing}"
    )


def _first_uses(text: str) -> tuple[int | None, int | None]:
    """Line numbers, comments left out, of the skill copy and of the first ``uv sync``."""
    lines = [line.strip() for line in text.splitlines()]
    code = [(n, line) for n, line in enumerate(lines) if not line.startswith("#")]
    return (
        next((n for n, line in code if line == SKILL_COPY), None),
        next((n for n, line in code if UV_SYNC.search(line)), None),
    )


@pytest.mark.parametrize("dockerfile", COPY_LINES)
def test_the_skill_is_copied_before_the_first_uv_sync(dockerfile):
    skill, sync = _first_uses((ROOT / dockerfile).read_text())
    assert skill is not None, f"{dockerfile} does not copy {SKILL_COPY!r}"
    assert sync is not None, f"{dockerfile} has no `uv sync`"
    assert skill < sync


@pytest.mark.parametrize(
    ("text", "ordered"),
    [
        (f"{SKILL_COPY}\nRUN {FIRST_SYNC}\n", True),
        (f"RUN {FIRST_SYNC}\n{SKILL_COPY}\n", False),
        # Any `uv sync` counts as the install, whatever its options or spacing.
        (f"RUN uv sync --no-dev\n{SKILL_COPY}\nRUN {FIRST_SYNC}\n", False),
        (f"RUN uv  sync\n{SKILL_COPY}\n", False),
        # Words in a comment are not the instruction.
        (f"# {SKILL_COPY}\nRUN {FIRST_SYNC}\n{SKILL_COPY}\n", False),
        (f"# run {FIRST_SYNC}\n{SKILL_COPY}\nRUN \\\n  {FIRST_SYNC}\n", True),
    ],
)
def test_the_order_check_reads_instructions_not_comments(text, ordered):
    skill, sync = _first_uses(text)
    assert skill is not None and sync is not None
    assert (skill < sync) is ordered
