@pytest.mark.asyncio
async def test_concurrent_claims_exactly_one_wins(store, call, monkeypatch):
    token_a = store.add_app("alpha", scopes=CLAIM_SCOPES)
    token_b = store.add_app("beta", scopes=CLAIM_SCOPES)
    ticket = store.add_ticket(revision=5)
    original = lease_svc.prepare_claim_worktree

    async def yielding_worktree(row: dict[str, Any]) -> dict[str, Any]:
        # Both callers pass the pre-checks before either reaches the CAS.
        await asyncio.sleep(0)
        await asyncio.sleep(0)
        return await original(row)

    monkeypatch.setattr(lease_svc, "prepare_claim_worktree", yielding_worktree)

    results = await asyncio.gather(
        call("task_claim", token_a, ref=_ref(ticket), revision=5),
        call("task_claim", token_b, ref=_ref(ticket), revision=5),
    )

    statuses = sorted(status for status, _ in results)
    assert statuses == [200, 409], results
    loser = next(envelope for status, envelope in results if status == 409)
    assert loser["code"] in {"stale_revision", "already_claimed"}
    assert len(_live_leases(store)) == 1
    assert len(_claimed_events(store)) == 1
    assert store.tickets[ticket["ticket_id"]]["revision"] == 6
    assert sorted(store.audit_codes()) == sorted(["ok", loser["code"]])


