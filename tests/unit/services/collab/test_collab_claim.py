CLAIM_SCOPES = ("read", "claim")


def _ref(ticket: dict[str, Any]) -> str:
    return f"t:{ticket['ticket_id']}"


def _expires(data: dict[str, Any]) -> datetime:
    value = datetime.fromisoformat(data["expires_at"])
    return value if value.tzinfo else value.replace(tzinfo=timezone.utc)


def _assert_refused(
    status: int, envelope: dict[str, Any], *, http: int, code: str, reason: str | None = None
) -> None:
    assert status == http, envelope
    assert envelope["ok"] is False
    assert envelope["code"] == code
    if reason is not None:
        assert envelope["message"].startswith(reason), envelope["message"]


def _claimed_events(store) -> list[dict[str, Any]]:
    return [event for event in store.events if event["action"] == "claimed"]


def _live_leases(store) -> list[dict[str, Any]]:
    return [row for row in store.leases.values() if row["state"] in {"active", "handoff_pending"}]


