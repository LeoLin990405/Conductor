async def _assert_claim_refused(store, call, token, ticket, *, http, code, reason):
    snapshot = copy.deepcopy(store.tickets)
    leases_before = copy.deepcopy(store.leases)
    events_before = len(store.events)
    status, envelope = await call(
        "task_claim", token, ref=_ref(ticket), revision=int(ticket["revision"])
    )
    _assert_refused(status, envelope, http=http, code=code, reason=reason)
    assert store.tickets == snapshot
    assert store.leases == leases_before
    assert len(store.events) == events_before
    assert store.audit[-1]["code"] == code
    return envelope


