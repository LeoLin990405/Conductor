@pytest.mark.asyncio
async def test_claim_happy_path_returns_schema_valid_lease(store, call):
    token = store.add_app("alpha", scopes=CLAIM_SCOPES)
    ticket = store.add_ticket(revision=3)
    before = datetime.now(timezone.utc)

    status, envelope = await call("task_claim", token, ref=_ref(ticket), revision=3)

    assert status == 200, envelope
    assert envelope["ok"] is True and envelope["code"] == "ok"
    data = envelope["data"]
    validate_tool_output("task_claim", data)
    assert data["ref"] == _ref(ticket)
    assert data["lease_id"] in store.leases
    assert data["worktree"] == {
        "path": f"/tmp/collab-wt/{ticket['ticket_id']}",
        "branch": f"conductor/ticket/{ticket['ticket_id']}",
        "base_sha": "b" * 40,
    }
    assert data["heartbeat_every_seconds"] == 60
    assert isinstance(data["rules"], list) and data["rules"]
    assert all(isinstance(rule, str) for rule in data["rules"])
    assert list(lease_svc.CLAIM_RULES) == data["rules"][: len(lease_svc.CLAIM_RULES)]
    ahead = (_expires(data) - before).total_seconds()
    assert 15 * 60 - 5 <= ahead <= 15 * 60 + 5
    assert "max_lease_until" in data

    stored = store.tickets[ticket["ticket_id"]]
    assert stored["status"] == "running"
    assert stored["revision"] == 4

    events = store.events_for(ticket["ticket_id"])
    assert len(events) == 1
    event = events[0]
    assert event["action"] == "claimed"
    assert event["actor"] == "app:alpha"
    assert event["to_owner"] == "app:alpha"
    assert event["detail"]["collab_event"] == "claimed"
    assert event["detail"]["assigned_by"] == "app_claim"
    assert event["detail"]["lease_id"] == data["lease_id"]

    assert len(store.audit) == 1
    row = store.audit[0]
    assert row["code"] == "ok"
    assert row["tool"] == "task_claim"
    assert row["app_id"] == "alpha"
    assert row["target"] == _ref(ticket)
    assert row["in_transaction"] is True


