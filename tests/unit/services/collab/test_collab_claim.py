@pytest.mark.asyncio
async def test_task_create_proposal_is_never_claimable(store, call):
    token = store.add_app("alpha", scopes=("read", "propose", "claim"))

    status, envelope = await call(
        "task_create",
        token,
        title="Document the claim flow",
        body="Write docs/collab/claim.md.",
        repo="/repo",
        write_scope=["docs/**"],
        acceptance=["docs build passes"],
        suggest_app_claimable=True,
    )

    assert status == 200, envelope
    view = envelope["data"]
    assert view["status"] == "awaiting_clarification"
    assert view["claimable"] is False
    assert view["claim_refusal"] == "not_app_claimable"
    ticket_id = view["ref"].split(":", 1)[1]
    stored = store.tickets[ticket_id]
    assert stored["status"] == "awaiting_clarification"
    collab = stored["mandate"]["collab"]
    assert collab["proposed_by"] == "app:alpha"
    assert collab["app_claimable"] is False
    assert collab["suggest_app_claimable"] is True
    assert collab["write_scope"] == ["docs/**"]
    assert stored["mandate"]["cwd"] == "/repo"
    assert store.audit_codes() == ["ok"]

    status, envelope = await call(
        "task_claim", token, ref=view["ref"], revision=int(view["revision"])
    )
    _assert_refused(status, envelope, http=409, code="not_claimable", reason="not_app_claimable")
    assert store.leases == {}
    assert store.events == []
    assert store.tickets[ticket_id]["status"] == "awaiting_clarification"

    status, envelope = await call("task_list", token)
    assert status == 200, envelope
    assert envelope["data"]["tasks"] == []



