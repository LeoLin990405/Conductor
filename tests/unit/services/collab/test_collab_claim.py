@pytest.mark.asyncio
async def test_task_list_filters(store, call):
    token = store.add_app("alpha", scopes=CLAIM_SCOPES)
    claimable = store.add_ticket(title="Claimable docs", revision=1)
    hidden = store.add_ticket(title="Not for apps", app_claimable=False)
    running = store.add_ticket(title="Already running", status="running")
    store.add_ticket(title="Someone else", user_id=OTHER_USER)

    status, envelope = await call("task_list", token)
    assert status == 200, envelope
    validate_tool_output("task_list", envelope["data"])
    refs = [task["ref"] for task in envelope["data"]["tasks"]]
    assert refs == [_ref(claimable)]
    (task,) = envelope["data"]["tasks"]
    assert task["claimable"] is True
    assert "claim_refusal" not in task
    assert "data.tasks[].body" in envelope["untrusted_fields"]
    assert "data.tasks[].acceptance[]" in envelope["untrusted_fields"]
    # App-authored at task_create, so data to read, never instructions.
    assert "data.tasks[].title" in envelope["untrusted_fields"]
    if "write_scope" in task:
        assert "data.tasks[].write_scope[]" in envelope["untrusted_fields"]
    if "repo" in task:
        assert "data.tasks[].repo" in envelope["untrusted_fields"]

    status, envelope = await call("task_list", token, claimable=False)
    assert status == 200, envelope
    validate_tool_output("task_list", envelope["data"])
    by_ref = {task["ref"]: task for task in envelope["data"]["tasks"]}
    assert set(by_ref) == {_ref(claimable), _ref(hidden), _ref(running)}
    assert by_ref[_ref(claimable)]["claimable"] is True
    assert by_ref[_ref(hidden)]["claimable"] is False
    assert by_ref[_ref(hidden)]["claim_refusal"] == "not_app_claimable"
    assert by_ref[_ref(running)]["claimable"] is False
    assert by_ref[_ref(running)]["claim_refusal"] == "not_queued"

    status, envelope = await call("task_list", token, kind="line")
    assert status == 200, envelope
    validate_tool_output("task_list", envelope["data"])
    assert envelope["data"]["tasks"] == []

    status, envelope = await call("task_claim", token, ref=_ref(claimable), revision=1)
    assert status == 200, envelope

    status, envelope = await call("task_list", token, claimable=False, mine=True)
    assert status == 200, envelope
    validate_tool_output("task_list", envelope["data"])
    (mine,) = envelope["data"]["tasks"]
    assert mine["ref"] == _ref(claimable)
    assert mine["owner"]["kind"] == "app_lease"
    assert mine["owner"]["id"] == "app:alpha"

    status, envelope = await call("task_list", token, mine=True)
    assert status == 200, envelope
    assert envelope["data"]["tasks"] == []


