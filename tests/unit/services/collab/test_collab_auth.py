def _text(value: Any) -> str:
    return json.dumps(value, default=str, sort_keys=True)


def assert_no_token(value: Any, tokens: list[str] | tuple[str, ...]) -> None:
    text = _text(value) if not isinstance(value, str) else value
    for token in tokens:
        assert token not in text


def assert_refusal(
    store,
    before: int,
    result: tuple[int, dict[str, Any]],
    *,
    code: str,
    status: int,
    app_id: str | None,
    tokens: tuple[str, ...] = (),
) -> dict[str, Any]:
    http_status, envelope = result
    assert http_status == status
    assert envelope["ok"] is False
    assert envelope["code"] == code
    assert len(store.audit) == before + 1, "exactly one new audit row"
    row = store.audit[-1]
    assert row["code"] == code
    assert row["http_status"] == status
    assert row["app_id"] == app_id
    assert_no_token(row, tokens)
    assert_no_token(envelope, tokens)
    return row


def full_app(store, app_id: str = "app-full") -> str:
    return store.add_app(app_id, scopes=ALL_SCOPES)


def arguments_for(tool: str) -> dict[str, Any]:
    """Schema-valid enough arguments; mode refusals happen before validation."""
    return {}


