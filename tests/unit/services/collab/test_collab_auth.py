@pytest.mark.asyncio
async def test_write_bucket_exhaustion_is_rate_limited(store, monkeypatch):
    token = full_app(store)
    frozen = RateLimiter(clock=lambda: 1000.0)
    headers = {"authorization": f"Bearer {token}"}
    # task_heartbeat only uses the write bucket (20/min). Each call is charged
    # before the (failing) schema check, so it needs no lease.
    for _ in range(20):
        status, envelope = await tools.invoke(
            "task_heartbeat", arguments={}, headers=headers, client_host="127.0.0.1", limiter=frozen
        )
        assert envelope["code"] != "rate_limited"
    before = len(store.audit)
    result = await tools.invoke(
        "task_heartbeat", arguments={}, headers=headers, client_host="127.0.0.1", limiter=frozen
    )
    row = assert_refusal(
        store, before, result, code="rate_limited", status=429, app_id="app-full", tokens=(token,)
    )
    assert row["rate_limited"] is True
    assert result[1]["retry_after"] > 0
    # Another write tool on the same app shares the exhausted bucket.
    status, envelope = await tools.invoke(
        "task_release", arguments={}, headers=headers, client_host="127.0.0.1", limiter=frozen
    )
    assert (status, envelope["code"]) == (429, "rate_limited")
    # Reads use their own bucket and still pass.
    status, envelope = await tools.invoke(
        "whoami", arguments={}, headers=headers, client_host="127.0.0.1", limiter=frozen
    )
    assert status == 200


