@pytest.mark.asyncio
async def test_no_plaintext_token_anywhere(store, call, monkeypatch, caplog, capsys):
    caplog.set_level(logging.DEBUG)
    tokens = [
        full_app(store),
        store.add_app("app-read", scopes=("read",)),
        store.add_app("app-revoked", scopes=ALL_SCOPES, revoked=True),
        store.add_app("app-disabled", scopes=ALL_SCOPES, enabled=False),
    ]
    stray = real_app_db.generate_token()
    service = real_app_db.generate_token()
    tokens += [stray, service]
    store.add_app("other", scopes=ALL_SCOPES)
    ticket = store.add_ticket()
    ref = f"t:{ticket['ticket_id']}"
    envelopes: list[dict[str, Any]] = []

    async def run(tool: str, token: str | None, **kwargs: Any) -> None:
        envelopes.append((await call(tool, token, **kwargs))[1])

    for token in tokens[:4] + [stray]:
        await run("whoami", token)
        await run("task_get", token, ref=ref)
        await run("task_claim", token, ref=ref)
        await run("whoami", token, headers={"X-Service-Token": service})
        await run("whoami", token, client_host="10.0.0.5")
        await run("whoami", token, headers={"X-Forwarded-For": "1.2.3.4"})
        await run("task_list", token, limit=0)
        await run("agent_ask", token, to="app:other", text="hi")
        await run("task_create", token, title="T title", body=f"x tok_{token} y", repo="/repo")
        await run("agent_ask", token, to="app:other", text=f"leak tok_{token}")
    monkeypatch.setenv("INTERNAL_SERVICE_TOKEN", service)
    await run("whoami", service)
    monkeypatch.setenv("CONDUCTOR_COLLAB_MODE", "off")
    await run("whoami", tokens[0])

    captured = capsys.readouterr()
    assert len(store.audit) == len(envelopes)
    for row in store.apps.values():
        assert HEX64.fullmatch(row["token_sha256"])
        for key in row:
            assert key in {
                "app_id", "user_id", "name", "token_sha256", "scopes", "can_write",
                "max_leases", "enabled", "revoked_at", "last_used_at", "created_at",
                "updated_at",
            }
    for token in tokens:
        assert token not in _text(store.audit)
        assert token not in _text(list(store.apps.values()))
        assert token not in _text(envelopes)
        assert token not in _text(store.messages)
        assert token not in _text(list(store.tickets.values()))
        assert token not in caplog.text
        assert token not in captured.out
        assert token not in captured.err
    # A digest is stored, but the token-bearing payloads were never stored.
    assert all("leak" not in message["text"] for message in store.messages)


